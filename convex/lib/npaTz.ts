export function timezoneForPhone(phone: string, fallback = "America/New_York"): string {
  const clean = phone.replace(/[^0-9]/g, "");
  const withoutCountry = clean.startsWith("1") && clean.length === 11 ? clean.substring(1) : clean;
  if (withoutCountry.length < 3) return fallback;
  const npa = withoutCountry.substring(0, 3);
  return NPA_TIMEZONE[npa] || fallback;
}
